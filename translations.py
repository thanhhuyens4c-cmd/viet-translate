def _load_json_translations():
    import os
    import json
    base_dir = os.path.dirname(os.path.abspath(__file__))
    for code in ('vi', 'en'):
        json_file = os.path.join(base_dir, 'i18n', f'{code}.json')
        if os.path.exists(json_file):
            try:
                with open(json_file, 'r', encoding='utf-8') as f:
                    data = json.load(f)
                    if isinstance(data, dict):
                        if code not in TRANSLATIONS:
                            TRANSLATIONS[code] = {}
                        for sec_k, sec_v in data.items():
                            if sec_k not in TRANSLATIONS[code]:
                                TRANSLATIONS[code][sec_k] = sec_v
                            elif isinstance(TRANSLATIONS[code][sec_k], dict) and isinstance(sec_v, dict):
                                TRANSLATIONS[code][sec_k].update(sec_v)
                            else:
                                TRANSLATIONS[code][sec_k] = sec_v
            except Exception:
                pass

_load_json_translations()


def t(key, lang='vi', **kwargs):
    """
    Look up a localized string key in dot notation (e.g. 'nav.find_translators').
    Falls back to 'vi' if not found in 'en', or returns the key if not found in either.
    Formats with kwargs if specified.
    """
    if not lang or lang not in ('vi', 'en'):
        lang = 'vi'

    parts = key.split('.')
    cur = TRANSLATIONS.get(lang, {})
    for p in parts:
        if isinstance(cur, dict) and p in cur:
            cur = cur[p]
        else:
            cur = None
            break

    # Fallback to Vietnamese if English missing
    if cur is None and lang != 'vi':
        cur = TRANSLATIONS.get('vi', {})
        for p in parts:
            if isinstance(cur, dict) and p in cur:
                cur = cur[p]
            else:
                cur = None
                break

    if cur is None:
        return key

    if kwargs and isinstance(cur, str):
        try:
            return cur.format(**kwargs)
        except Exception:
            return cur

    return cur


def get_localized_languages(lang='vi'):
    """
    Returns the list of languages formatted for templates, with names localized
    to the active language.
    """
    is_en = (lang == 'en')
    result = []
    for item in LOCALIZED_LANGUAGES_DATA:
        display_name = item['name_en'] if is_en else item['name_vi']
        short_name = item['short_name_en'] if is_en else item['short_name_vi']
        cert = item['cert_en'] if is_en else item['cert_vi']
        flag_alt = f"{short_name} flag" if is_en else f"Quốc kỳ {short_name}"
        
        entry = {
            'name': display_name,
            'name_vi': item['name_vi'],
            'name_en': item['name_en'],
            'flag': item['flag'],
            'cert': cert,
            'code': item['code'],
            'short_name': short_name,
            'code_lower': item['code_lower'],
            'flag_svg': f"/static/flags/{item['code_lower']}.svg",
            'flag_alt': flag_alt,
            'slug': item['slug']
        }
        result.append(entry)
    return result


def get_language_display_name(name, lang='vi'):
    """
    Maps a stored Vietnamese language name (e.g. 'Tiếng Nhật', as saved on Job/Service
    records) to its localized display name. Falls back to the original value when the
    active language is Vietnamese or when no match is found (e.g. free-text values).
    """
    if lang != 'en' or not name:
        return name
    for item in LOCALIZED_LANGUAGES_DATA:
        if item['name_vi'] == name:
            return item['name_en']
    return name
